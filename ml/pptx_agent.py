            'Принимай решения самостоятельно на основе имеющейся информации, не спрашивай разрешения у пользователя',
            'Если информации недостаточно, используй свое экспертное мнение вместо запроса дополнительных данных',
            'ВАЖНО: При создании нового слайда с элементами всегда сначала вызывай slide_agent для создания слайда, а затем уже вызывай других агентов для добавления элементов на этот слайд. Если после создания слайда нужно добавить элементы на этот же слайд, то добавляй их на уже созданный слайд.',
